@app.cell
def _(E, EV, WORK, json, os):
    import torch
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    if device.type == "cuda":
        torch.backends.cudnn.benchmark = False
    PROFILE = os.environ.get("PMP_PROFILE") or ("paper" if device.type == "cuda" else "smoke")
