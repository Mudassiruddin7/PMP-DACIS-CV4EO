    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "host.json").write_text(json.dumps({"profile": PROFILE, "host": HOST, "cfg": {k: v for k, v in CFG.items()}}, indent=1, default=str))
    print("profile:", PROFILE)
    print("host   :", HOST)
