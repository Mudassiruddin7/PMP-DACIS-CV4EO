@app.cell
def _(CACHE, CFG, DATA, E, OUT, PROFILE, device, time):
    VARIANTS = ("resisc45", "eurosat13", "eurosat3", "plantvillage")
    TIERS = (1, 2, 3) if PROFILE in ("paper", "micro") else (1,)
    _fh = open(OUT / "log.txt", "a")
    _t0 = time.time()
